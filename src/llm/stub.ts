import type Anthropic from "@anthropic-ai/sdk";
import type { LlmProvider, StructuredRequest } from "@/llm/types";

const INTENT_PATTERNS: Array<[string, RegExp]> = [
  ["question", /\?|^(what|why|how|when|where|who|could|would|can|do|does|did)\b/i],
  ["request", /\b(can you|could you|would you|please|i need|i'd like|asking for)\b/i],
  ["apology", /\b(sorry|apolog|my fault|i regret)\b/i],
  ["explanation", /\b(because|the reason|that's why|due to|since)\b/i],
  ["commitment", /\b(i will|i'll|i promise|by (monday|tuesday|wednesday|thursday|friday|tomorrow))\b/i],
  ["disagreement", /\b(but|however|i disagree|that's not|actually)\b/i],
  ["gratitude", /\b(thank|thanks|appreciate)\b/i],
  ["greeting", /^(hi|hello|hey|good (morning|afternoon|evening))\b/i],
];

const STOP_WORDS = new Set([
  "about", "after", "again", "also", "and", "are", "because", "been", "before", "being", "but",
  "can", "could", "did", "does", "for", "from", "had", "has", "have", "how", "into", "its",
  "just", "like", "more", "not", "now", "only", "other", "our", "out", "over", "same", "should",
  "some", "such", "than", "that", "the", "their", "them", "then", "there", "these", "they",
  "this", "those", "through", "too", "under", "very", "was", "were", "what", "when", "which",
  "while", "who", "will", "with", "would", "you", "your",
]);

/**
 * Deterministic provider used when no API key is configured, and by the engine's own tests.
 * It exists so every deterministic component (§46) can be exercised without network calls;
 * its language quality is irrelevant because the scenarios are system tests (§44).
 */
export function createStubProvider(): LlmProvider {
  return {
    name: "stub",

    async structured<T>(request: StructuredRequest<T>): Promise<T> {
      const lastUser = lastUserText(request.messages);
      const draft = draftFor(request.label, lastUser, request.messages);
      const parsed = request.schema.safeParse(draft);
      if (parsed.success) return parsed.data;
      // Falling back to the schema's own defaults keeps the stub usable for labels it
      // does not model explicitly.
      return request.schema.parse(emptyDraftFor(draft));
    },

    /**
     * Returns a fixed line rather than echoing the prompt: the renderer's prompt carries
     * hidden state and retrieved memories, and echoing it would leak them into dialogue.
     */
    async text(): Promise<string> {
      return "I hear you. Say more about what you need before I answer.";
    },
  };
}

function draftFor(label: string, lastUser: string, messages: Anthropic.MessageParam[]): unknown {
  switch (label) {
    case "interpreter":
      return {
        intents: detectIntents(lastUser),
        topics: keywords(lastUser, 3),
        referencedEntities: [],
        inferredSignals: {
          directness: round(clamp01(lastUser.split(/\s+/).length / 40)),
          uncertainty: /\b(maybe|might|not sure|i think|possibly)\b/i.test(lastUser) ? 0.7 : 0.2,
        },
        proposedStateChanges: [],
        triggeredFacts: [],
        confidence: 0.4,
      };
    case "decision":
      return {
        intent: detectIntents(lastUser)[0] ?? "acknowledge",
        emotionalResponse: "neutral",
        responseStrategy: "ask_clarifying_question",
        usedMemoryIds: [],
        proposedStateChanges: [],
        wantsToEndConversation: messages.length > 24,
      };
    case "memory_extraction":
      return { memories: [] };
    default:
      return {
        summary: `Stub evaluation over ${messages.length} prompt message(s).`,
        scores: {},
        notes: ["Generated by the stub LLM provider; not a real assessment."],
      };
  }
}

function emptyDraftFor(draft: unknown): unknown {
  return typeof draft === "object" && draft !== null ? {} : draft;
}

function lastUserText(messages: Anthropic.MessageParam[]): string {
  for (let index = messages.length - 1; index >= 0; index -= 1) {
    const message = messages[index];
    if (!message || message.role !== "user") continue;
    if (typeof message.content === "string") return message.content;
    const text = message.content
      .filter((block): block is Anthropic.TextBlockParam => block.type === "text")
      .map((block) => block.text)
      .join("\n");
    if (text) return text;
  }
  return "";
}

function detectIntents(text: string): string[] {
  const intents = INTENT_PATTERNS.filter(([, pattern]) => pattern.test(text)).map(([intent]) => intent);
  return intents.length > 0 ? intents : ["statement"];
}

function keywords(text: string, limit: number): string[] {
  const counts = new Map<string, number>();
  for (const token of text.toLowerCase().split(/[^a-z0-9]+/)) {
    if (token.length < 4 || STOP_WORDS.has(token)) continue;
    counts.set(token, (counts.get(token) ?? 0) + 1);
  }
  return [...counts.entries()]
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .slice(0, limit)
    .map(([token]) => token);
}

function clamp01(value: number): number {
  return Math.min(1, Math.max(0, value));
}

function round(value: number): number {
  return Math.round(value * 100) / 100;
}
